// Renders scenes.html frame by frame and pipes the frames into ffmpeg.
// Usage: node render.js [output.mp4]
const { chromium } = require('playwright');
const { spawn, execFileSync } = require('child_process');
const path = require('path');
const fs = require('fs');

const FPS = 30;
const out = process.argv[2] || path.join(__dirname, 'what-is-a-prompt.mp4');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1.5 });
  await page.goto('file://' + path.join(__dirname, 'scenes.html'));
  await page.evaluate(() => document.fonts.ready);
  const duration = await page.evaluate(() => window.DURATION);

  // Sidecar subtitles (they are also burned into the video by scenes.html)
  const cues = await page.evaluate(() => window.CUES);
  const ts = sec => {
    const ms = Math.round(sec * 1000), p = (n, w = 2) => String(n).padStart(w, '0');
    return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
  };
  [['he', 2], ['en', 3]].forEach(([lang, col]) => fs.writeFileSync(
    out.replace(/\.mp4$/, '') + `.${lang}.srt`,
    cues.map((c, i) => `${i + 1}\n${ts(c[0])} --> ${ts(c[1])}\n${c[col]}\n`).join('\n')));

  execFileSync('python3', ['music.py', String(duration)], { cwd: __dirname });
  const music = path.join(__dirname, 'music.wav');
  // English voice-over, generated by narration.py (needs the Kokoro model files)
  const voice = path.join(__dirname, 'narration.wav');

  const ffmpeg = spawn('ffmpeg', [
    '-y', '-f', 'image2pipe', '-framerate', String(FPS), '-c:v', 'mjpeg', '-i', '-',
    '-i', music, '-i', voice,
    // keep the music well under the voice and duck it further while speaking
    '-filter_complex', '[2:a]aresample=44100,asplit[v1][v2];' +
      '[1:a]volume=0.3[mq];[mq][v1]sidechaincompress=threshold=0.02:ratio=4:attack=30:release=600[m];' +
      '[m][v2]amix=inputs=2:normalize=0,volume=4dB,alimiter=limit=0.84:level=false[a]',
    '-map', '0:v', '-map', '[a]', '-c:a', 'aac', '-b:a', '160k', '-shortest',
    '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '20', '-preset', 'medium',
    '-movflags', '+faststart', out,
  ], { stdio: ['pipe', 'inherit', 'inherit'] });

  const frames = Math.round(duration * FPS);
  for (let i = 0; i < frames; i++) {
    await page.evaluate(t => window.render(t), i / FPS);
    const buf = await page.screenshot({ type: 'jpeg', quality: 92 });
    if (!ffmpeg.stdin.write(buf)) await new Promise(r => ffmpeg.stdin.once('drain', r));
    if (i % 150 === 0) console.log(`frame ${i}/${frames}`);
  }
  ffmpeg.stdin.end();
  await new Promise(r => ffmpeg.on('close', r));
  await browser.close();
  console.log('wrote', out);
})();
